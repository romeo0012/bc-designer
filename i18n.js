// Překlad textu; {x} v textu se nahradí hodnotou z vars
function T(cs, vars) {
  let s = (LANG === "en" && Object.prototype.hasOwnProperty.call(EN, cs)) ? EN[cs] : cs;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}
// Role ve tvaru "Kategorie (detail)"
function trRole(role) {
  const r = String(role), k = r.indexOf(" (");
  return k < 0 ? T(r) : T(r.slice(0, k)) + " (" + T(r.slice(k + 2, -1)) + ")";
}
